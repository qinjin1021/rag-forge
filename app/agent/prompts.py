def build_context(chunks: list) -> str:
    """把检索片段组装为带编号的上下文(编号即引用角标)"""
    parts = []
    for i, chunk in enumerate(chunks, start=1):
        snippet = chunk.text.strip()
        parts.append(f"[{i}] (来源: {chunk.source})\n{snippet}")
    return "\n\n".join(parts)
